#!/usr/bin/env node
// Prints the Axiom dashboard document (schemaVersion 2) for Claude Code telemetry. Writes setup/axiom/dashboard.json
// with --write. --dataset NAME overrides the events dataset (default: AXIOM_DATASET or claude-logs).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { queries } from "./apl.mjs";
const args = process.argv.slice(2);
const ds = args.includes("--dataset") ? args[args.indexOf("--dataset") + 1] : (process.env.AXIOM_DATASET || "claude-logs");
const q = queries(ds);
const chart = (id, type, name, apl, extra = {}) => ({ id, type, name, query: { apl }, ...extra });
const charts = [
  { id: "about", type: "Note", text: `Claude Code telemetry from the Boostly fulfillment machines (dataset **${ds}**). Split by **operator** (travisse, karissa). Tool events carry name, duration and success only; prompt text and tool arguments are never exported. See docs/telemetry.md in boostly-branding-workflow; the per-run join is generated by setup/axiom/run-join.mjs.` },
  chart("tool-duration", "Table", "Tool duration p50/p95 by tool and operator", q.toolDuration),
  chart("tool-duration-series", "TimeSeries", "Tool duration p95 over time", q.toolDurationSeries),
  chart("slowest-sessions", "Table", "Slowest sessions (wall time, tool time, API time, cost)", q.slowestSessions),
  chart("tool-errors", "Table", "Tool error rate by tool and operator", q.toolErrors),
  chart("tool-error-types", "Table", "Tool errors by type", q.toolErrorTypes),
  chart("cost-per-day", "TimeSeries", "Cost per day by operator (USD)", q.costPerDay),
  chart("tokens-per-session", "Table", "Tokens and cost per session", q.tokensPerSession),
  chart("api-latency", "TimeSeries", "API latency p50/p95 by operator", q.apiLatencySeries),
  chart("api-latency-model", "Table", "API latency and errors by model", q.apiLatencyByModel),
];
const layout = [
  { i: "about", x: 0, y: 0, w: 12, h: 2 },
  { i: "tool-duration", x: 0, y: 2, w: 6, h: 8 }, { i: "tool-duration-series", x: 6, y: 2, w: 6, h: 8 },
  { i: "slowest-sessions", x: 0, y: 10, w: 12, h: 8 },
  { i: "tool-errors", x: 0, y: 18, w: 6, h: 8 }, { i: "tool-error-types", x: 6, y: 18, w: 6, h: 8 },
  { i: "cost-per-day", x: 0, y: 26, w: 6, h: 7 }, { i: "api-latency", x: 6, y: 26, w: 6, h: 7 },
  { i: "tokens-per-session", x: 0, y: 33, w: 12, h: 8 },
  { i: "api-latency-model", x: 0, y: 41, w: 12, h: 6 },
];
const dashboard = {
  name: "Claude Code: Boostly fulfillment",
  owner: "X-AXIOM-EVERYONE",
  description: "Tool durations, failures, API latency, tokens and cost per session, split by operator (travisse, karissa).",
  uid: "boostly-claude-code",
  schemaVersion: 2,
  refreshTime: 60,
  timeWindowStart: "qr-now-7d",
  timeWindowEnd: "qr-now",
  charts,
  layout,
};
const out = JSON.stringify(dashboard, null, 2) + "\n";
if (args.includes("--write")) fs.writeFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), "dashboard.json"), out);
else process.stdout.write(out);
